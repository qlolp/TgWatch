#!/bin/bash
# Local universal build only: ad-hoc signing is not Developer ID signing or notarization.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
output="$root/build/macos/TgWatch.app"
if [[ $# -gt 0 ]]; then
  if [[ $# -ne 2 || "$1" != --output ]]; then
    echo 'Usage: bash scripts/build-mac-app.sh [--output /absolute/path/TgWatch.app]' >&2
    exit 2
  fi
  output=$2
fi
case "$output" in /*.app) ;; *) echo 'Output must be an absolute .app path' >&2; exit 2 ;; esac
if [[ -L "$output" ]]; then echo 'Refusing to replace a symlink' >&2; exit 2; fi
if [[ -e "$output" && ! -f "$output/Contents/Resources/tgwatch-local-build" ]]; then
  echo 'Output exists and was not made by this builder. Choose another path.' >&2; exit 2
fi
parent=$(dirname "$output")
mkdir -p "$parent"
stage=$(mktemp -d "${TMPDIR:-/tmp}/tgwatch-mac-build.XXXXXX")
trap 'rm -rf -- "$stage"' EXIT
module_cache="${TGWATCH_MAC_MODULE_CACHE:-$root/build/macos/module-cache}"
mkdir -p "$module_cache"
app="$stage/TgWatch.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
sdk=$(xcrun --sdk macosx --show-sdk-path)
sources=("$root"/macos/TgWatch/*.swift)
for arch in arm64 x86_64; do
  xcrun swiftc -swift-version 5 -parse-as-library -O -sdk "$sdk" -target "${arch}-apple-macosx13.0" \
    -module-cache-path "$module_cache" "${sources[@]}" \
    -framework AppKit -framework UserNotifications -framework ServiceManagement -o "$stage/TgWatch-$arch"
done
/usr/bin/lipo -create "$stage/TgWatch-arm64" "$stage/TgWatch-x86_64" -output "$app/Contents/MacOS/TgWatch"
cp "$root/macos/TgWatch/Info.plist" "$app/Contents/Info.plist"
cp "$root/scripts/regional-services.py" "$app/Contents/Resources/"
cp "$root/docs/macos.md" "$app/Contents/Resources/"
cp "$root/LICENSE" "$app/Contents/Resources/"
for localization in "$root"/macos/TgWatch/*.lproj; do
  if [[ -d "$localization" ]]; then cp -R "$localization" "$app/Contents/Resources/"; fi
done
printf 'Generated by the TgWatch local app builder\n' > "$app/Contents/Resources/tgwatch-local-build"
/usr/bin/plutil -lint "$app/Contents/Info.plist"
/usr/bin/codesign --force --sign - --options runtime --timestamp=none "$app"
/usr/bin/codesign --verify --strict "$app"
/usr/bin/ditto -c -k --keepParent "$app" "$stage/TgWatch-mac-local-build.zip"
if [[ -e "$output" ]]; then mv "$output" "$stage/previous.app"; fi
mv "$app" "$output"
mv "$stage/TgWatch-mac-local-build.zip" "$parent/TgWatch-mac-local-build.zip"
if ! /usr/bin/codesign --verify --strict "$output"; then
  echo 'App signature verification failed at the destination. Use the validated archive and extract outside synchronized folders.' >&2
fi
printf 'Built %s (local ad-hoc signature; Python3.10+ required)\n' "$parent/TgWatch-mac-local-build.zip"
