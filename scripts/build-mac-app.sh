#!/bin/bash
# Pinned standalone Python downloads and optional, explicitly configured macOS signing.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
output="$root/build/macos/TgWatch.app"
python_tag=20261026
python_version=3.11.18
arm64_archive="cpython-${python_version}+${python_tag}-aarch64-apple-darwin-install_only.tar.gz"
x86_64_archive="cpython-${python_version}+${python_tag}-x86_64-apple-darwin-install_only.tar.gz"
arm64_sha256=cba3455e18516fbe8668cff2820c9b6a53447c552d612443c2b2fb60d390a908
x86_64_sha256=a85474bcc78a98ca6b0070d8d615b0494b912b960239e6f18cc12d648f2dc270
sign_identity=${TGWATCH_MAC_SIGN_IDENTITY:-}
notary_key_file=${TGWATCH_MAC_NOTARY_KEY_FILE:-}
notary_key_id=${TGWATCH_MAC_NOTARY_KEY_ID:-}
notary_issuer=${TGWATCH_MAC_NOTARY_ISSUER:-}
notary_configured=false
if [[ -n "$notary_key_file" || -n "$notary_key_id" || -n "$notary_issuer" ]]; then
  if [[ -z "$notary_key_file" || -z "$notary_key_id" || -z "$notary_issuer" || -z "$sign_identity" ]]; then
    echo 'Notarization requires a signing identity and all TGWATCH_MAC_NOTARY_* settings.' >&2
    exit 2
  fi
  if [[ "$notary_key_file" != /* || ! -f "$notary_key_file" || ! -r "$notary_key_file" ]]; then
    echo 'TGWATCH_MAC_NOTARY_KEY_FILE must name a readable external .p8 key file.' >&2
    exit 2
  fi
  notary_configured=true
fi
if [[ $# -gt 0 ]]; then
  if [[ $# -ne 2 || "$1" != --output ]]; then
    echo 'Usage: bash scripts/build-mac-app.sh [--output /absolute/path/TgWatch.app]' >&2
    exit 2
  fi
  output=$2
fi
case "$output" in /*.app) ;; *) echo 'Output must be an absolute .app path' >&2; exit 2 ;; esac
if [[ -L "$output" ]]; then echo 'Refusing to replace a symlink' >&2; exit 2; fi
if [[ -e "$output" && ! -f "$output/Contents/Resources/tgwatch-local-build" ]]; then
  echo 'Output exists and was not made by this builder. Choose another path.' >&2; exit 2
fi
parent=$(dirname "$output")
mkdir -p "$parent"
stage=$(mktemp -d "${TMPDIR:-/tmp}/tgwatch-mac-build.XXXXXX")
trap 'rm -rf -- "$stage"' EXIT
module_cache="${TGWATCH_MAC_MODULE_CACHE:-$root/build/macos/module-cache}"
mkdir -p "$module_cache"
app="$stage/TgWatch.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
download_python() {
  local archive=$1 expected=$2
  local url="https://github.com/astral-sh/python-build-standalone/releases/download/${python_tag}/${archive/+/%2B}"
  curl --fail --location --retry 3 --silent --show-error --output "$stage/$archive" "$url"
  (cd "$stage" && printf '%s  %s\n' "$expected" "$archive" | /usr/bin/shasum -a 256 --check --status)
}
download_python "$arm64_archive" "$arm64_sha256"
download_python "$x86_64_archive" "$x86_64_sha256"
for arch in arm64 x86_64; do
  mkdir -p "$stage/python-$arch"
done
tar -xzf "$stage/$arm64_archive" -C "$stage/python-arm64"
tar -xzf "$stage/$x86_64_archive" -C "$stage/python-x86_64"
mkdir -p "$app/Contents/Resources/python"
for arch in arm64 x86_64; do
  runtime="$stage/python-$arch/python"
  if [[ ! -x "$runtime/bin/python3" ]] || ! /usr/bin/lipo -archs "$runtime/bin/python3" | grep -qw "$arch"; then
    echo "Pinned Python archive does not contain its expected $arch runtime." >&2
    exit 1
  fi
  mv "$runtime" "$app/Contents/Resources/python/$arch"
done
sdk=$(xcrun --sdk macosx --show-sdk-path)
sources=("$root"/macos/TgWatch/*.swift)
for arch in arm64 x86_64; do
  xcrun swiftc -swift-version 5 -parse-as-library -O -sdk "$sdk" -target "${arch}-apple-macosx13.0" \
    -module-cache-path "$module_cache" "${sources[@]}" \
    -framework AppKit -framework UserNotifications -framework ServiceManagement -o "$stage/TgWatch-$arch"
done
/usr/bin/lipo -create "$stage/TgWatch-arm64" "$stage/TgWatch-x86_64" -output "$app/Contents/MacOS/TgWatch"
cp "$root/macos/TgWatch/Info.plist" "$app/Contents/Info.plist"
cp "$root/scripts/regional-services.py" "$app/Contents/Resources/"
cp "$root/docs/macos.md" "$app/Contents/Resources/"
cp "$root/LICENSE" "$app/Contents/Resources/"
for localization in "$root"/macos/TgWatch/*.lproj; do
  if [[ -d "$localization" ]]; then cp -R "$localization" "$app/Contents/Resources/"; fi
done
printf 'Generated by the TgWatch local app builder\n' > "$app/Contents/Resources/tgwatch-local-build"
/usr/bin/plutil -lint "$app/Contents/Info.plist"
sign_code() {
  if [[ -n "$sign_identity" ]]; then
    /usr/bin/codesign --force --options runtime --timestamp --sign "$sign_identity" "$1"
  else
    /usr/bin/codesign --force --sign - --options runtime --timestamp=none "$1"
  fi
}
while IFS= read -r -d '' binary; do
  if /usr/bin/file -b "$binary" | grep -q 'Mach-O'; then sign_code "$binary"; fi
done < <(find "$app/Contents/Resources/python" -type f -print0)
sign_code "$app/Contents/MacOS/TgWatch"
if [[ -n "$sign_identity" ]]; then
  /usr/bin/codesign --force --options runtime --timestamp --sign "$sign_identity" "$app"
  archive_name=TgWatch-mac-developer-id-build.zip
else
  /usr/bin/codesign --force --options runtime --timestamp=none --sign - "$app"
  archive_name=TgWatch-mac-local-build.zip
fi
/usr/bin/codesign --verify --deep --strict "$app"
/usr/bin/ditto -c -k --keepParent "$app" "$stage/$archive_name"
if [[ "$notary_configured" == true ]]; then
  if ! xcrun notarytool submit "$stage/$archive_name" --key "$notary_key_file" \
      --key-id "$notary_key_id" --issuer "$notary_issuer" --wait --output-format json \
      > "$stage/notary-result.json" 2> "$stage/notary-error.txt"; then
    echo 'Apple notary submission failed; no notarized build was produced.' >&2
    exit 1
  fi
  if ! grep -Eq '"status"[[:space:]]*:[[:space:]]*"Accepted"' "$stage/notary-result.json"; then
    echo 'Apple notary service did not return Accepted; no stapling was performed.' >&2
    exit 1
  fi
  xcrun stapler staple "$app" >/dev/null
  xcrun stapler validate "$app" >/dev/null
  /usr/sbin/spctl --assess --type execute --verbose=2 "$app" >/dev/null
  archive_name=TgWatch-mac-notarized-build.zip
  /usr/bin/ditto -c -k --keepParent "$app" "$stage/$archive_name"
fi
if [[ -e "$output" ]]; then mv "$output" "$stage/previous.app"; fi
mv "$app" "$output"
mv "$stage/$archive_name" "$parent/$archive_name"
if ! /usr/bin/codesign --verify --deep --strict "$output"; then
  echo 'App signature verification failed at the destination. Use the validated archive and extract outside synchronized folders.' >&2
fi
if [[ "$notary_configured" == true ]]; then
  printf 'Built and notarized %s\n' "$parent/$archive_name"
elif [[ -n "$sign_identity" ]]; then
  printf 'Built %s (Developer ID signed; not notarized)\n' "$parent/$archive_name"
else
  printf 'Built %s (local ad-hoc signature; not notarized)\n' "$parent/$archive_name"
fi
