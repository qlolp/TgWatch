#!/usr/bin/env python3
"""Freeze the release tooling requirements with every published artifact hash.

CI installs the generated lock with --require-hashes, so a republished or substituted
distribution cannot reach a job that later handles the signing key. Regenerate after every
change to requirements-release.txt.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import urllib.request

CONTINUATION = " " + chr(92)


def normalized_name(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def check_lock(requirements, output):
    """Reject stale direct pins or unhashed packages without contacting pip or PyPI."""
    direct, locked, hashed = {}, {}, set()
    current = None
    for path, pins, is_lock in ((requirements, direct, False), (output, locked, True)):
        for line in path.read_text().splitlines():
            text = line.strip().removesuffix(chr(92)).strip()
            if not text or text.startswith("#"):
                continue
            if is_lock and re.fullmatch(r"--hash=sha256:[0-9a-f]{64}", text):
                if current is None:
                    raise ValueError("Lock hash has no package pin")
                hashed.add(current)
                continue
            match = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s=]+)", text)
            if not match:
                raise ValueError(f"Unsupported requirement {text!r}; regenerate the hash lock")
            name, version = match.groups()
            key = normalized_name(name)
            if key in pins:
                raise ValueError(f"Duplicate requirement {name}; regenerate the hash lock")
            pins[key] = (name, version)
            if is_lock:
                current = key
    if not direct or not locked:
        raise ValueError("Requirements and lock must both contain package pins")
    for key, (name, version) in direct.items():
        if key not in locked or locked[key][1] != version:
            raise ValueError(f"Lock does not contain {name}=={version}; regenerate with "
                             "python3 scripts/lock-requirements.py scripts/requirements-release.txt "
                             "scripts/requirements-release.lock")
    if set(locked) != hashed:
        raise ValueError("Every locked package requires a SHA256 artifact hash; regenerate the lock")
    return len(locked)


def resolve(requirements, python):
    result = subprocess.run(
        [python, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
         "--report", "-", "-r", str(requirements)],
        text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f"pip could not resolve {requirements}: {result.stderr.strip()}")
    report = json.loads(result.stdout)
    pins = {}
    for item in report.get("install", []):
        metadata = item.get("metadata", {})
        name, version = metadata.get("name"), metadata.get("version")
        if not isinstance(name, str) or not isinstance(version, str):
            raise ValueError("Resolved package without a name and version")
        pins[normalized_name(name)] = (name, version)
    if not pins:
        raise ValueError("Refusing an empty lock")
    return pins


def artifact_hashes(name, version):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        payload = json.load(response)
    digests = sorted({url["digests"]["sha256"] for url in payload.get("urls", [])
                      if re.fullmatch(r"[0-9a-f]{64}", url.get("digests", {}).get("sha256", ""))})
    if not digests:
        raise ValueError(f"PyPI published no artifacts for {name}=={version}")
    return digests


def requirement(name, version, digests):
    hashes = [f"    --hash=sha256:{digest}" for digest in digests]
    continued = [line + CONTINUATION for line in hashes[:-1]]
    return "\n".join([f"{name}=={version} {CONTINUATION}"] + continued + [hashes[-1]])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("requirements")
    parser.add_argument("output")
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--check", action="store_true", help="Check direct pins and lock hashes offline")
    args = parser.parse_args()
    if args.check:
        try:
            count = check_lock(Path(args.requirements), Path(args.output))
        except (ValueError, OSError) as error:
            print(f"Release requirements lock refused: {error}", file=sys.stderr)
            return 1
        print(f"Checked {count} hashed packages against {args.requirements}")
        return 0
    pins = resolve(Path(args.requirements), args.python)
    lines = [
        "# Generated by scripts/lock-requirements.py from " + Path(args.requirements).name + ".",
        "# Every hash PyPI published for each pinned version is listed; install with --require-hashes.",
    ]
    for key in sorted(pins):
        name, version = pins[key]
        lines.append(requirement(name, version, artifact_hashes(name, version)))
    Path(args.output).write_text("\n".join(lines) + "\n")
    print(f"Locked {len(pins)} packages into {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
